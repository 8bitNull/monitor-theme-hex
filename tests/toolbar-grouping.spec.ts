 await expect(controls.getByRole('combobox',{name:'状态',exact:true})).toHaveAttribute('data-value','online')
 await expect(page.getByRole('group',{name:'系统快速筛选'}).getByRole('button',{name:'Windows',exact:true})).toHaveAttribute('aria-pressed','true')
