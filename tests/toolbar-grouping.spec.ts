test('desktop separates display settings from a unified filter row',async({page})=>{
 await page.route('**/api/nodes',r=>r.fulfill({json:{nodes:nodes().map((n,i)=>({...n,group:i<3?'网站':'流量'}))}}))
 await page.setViewportSize({width:1024,height:1000});await page.goto('/')
 const toolbar=page.locator('.desktop-results-toolbar'),primary=toolbar.locator('.node-toolbar-primary'),filters=toolbar.locator('.node-browser'),controls=toolbar.locator('.desktop-browse-controls')
 await expect(primary.getByRole('heading',{name:'节点',exact:true})).toBeVisible()
 await expect(controls.getByRole('combobox',{name:'节点分组',exact:true})).toBeVisible()
 await expect(controls.getByRole('combobox',{name:'地区',exact:true})).toBeVisible()
 await expect(primary.getByRole('combobox',{name:'地区',exact:true})).toHaveCount(0)
 expect(await toolbar.evaluate(el=>getComputedStyle(el).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
 await expect(primary.getByRole('button',{name:'卡片视图',exact:true})).toBeVisible()
 await expect(primary.getByRole('combobox',{name:'卡片密度',exact:true})).toBeVisible()
 await chooseOption(primary.getByRole('combobox',{name:'卡片密度',exact:true}),'compact')
 await expect(filters).toBeHidden()
 const centers=await primary.locator('h2,[role=combobox],.view-switch').evaluateAll(elements=>elements.map(el=>{const b=el.getBoundingClientRect();return b.y+b.height/2}))
 expect(Math.max(...centers)-Math.min(...centers)).toBeLessThanOrEqual(2)
 const controlBoxes=await controls.locator('.node-search-control,[role=combobox]').evaluateAll(elements=>elements.map(el=>{const b=el.getBoundingClientRect();return {center:b.y+b.height/2,height:b.height}}))
 expect(controlBoxes).toHaveLength(4)
 expect(Math.max(...controlBoxes.map(b=>b.center))-Math.min(...controlBoxes.map(b=>b.center))).toBeLessThanOrEqual(2)
 expect(controlBoxes.map(b=>b.height)).toEqual([38,38,38,38])
 expect((await controls.boundingBox())!.y).toBeGreaterThan((await primary.boundingBox())!.y)
 await expect(primary.locator('.results-count')).toHaveText('6')
 await expect(controls.getByRole('button',{name:'重置筛选',exact:true})).toHaveCount(0)
 await page.getByRole('searchbox').fill('Tokyo')
 // The shared focus ring belongs to the search control, not to a second inset box.
 expect(await controls.getByRole('searchbox').evaluate(el=>getComputedStyle(el).outlineStyle)).toBe('none')
 expect(await controls.locator('.node-search-control').evaluate(el=>getComputedStyle(el).boxShadow)).not.toBe('none')
 await expect(primary.locator('.results-count')).toHaveText('1 / 6')
 await expect(filters.locator('.active-filters')).toContainText('Tokyo')
 const positions=await page.locator('.map-frame,.node-toolbar-primary,.node-browser,.node-grid').evaluateAll(elements=>elements.map(el=>el.getBoundingClientRect().top))
 expect(positions).toHaveLength(4);expect(positions).toEqual([...positions].sort((a,b)=>a-b))
 await primary.getByRole('button',{name:'表格视图',exact:true}).click()
 await expect(primary.locator('.table-tools-host').getByRole('button',{name:'恢复默认列',exact:true})).toBeVisible()
 await expect(primary.locator('.desktop-card-density')).toHaveCount(0)
 const tableCenters=await primary.locator('h2,[role=combobox],.view-switch,.table-reset-columns').evaluateAll(elements=>elements.map(el=>{const b=el.getBoundingClientRect();return b.y+b.height/2}))
 expect(Math.max(...tableCenters)-Math.min(...tableCenters)).toBeLessThanOrEqual(2)
 await page.locator('.table-node-name').first().click();await page.getByRole('button',{name:'返回总览',exact:true}).click()
 await expect(primary.locator('.table-tools-host .table-reset-columns')).toBeVisible()
 await expect(controls.getByRole('searchbox')).toHaveValue('Tokyo')
 await controls.getByRole('searchbox').fill('does-not-exist')
 await expect(primary.locator('.results-count')).toHaveText('0 / 6')
 await expect(page.getByText('没有符合条件的节点',{exact:true})).toBeVisible()
 await controls.getByRole('button',{name:'重置筛选',exact:true}).click()
 await expect(primary.locator('.results-count')).toHaveText('6')
 await expect(controls.getByRole('searchbox')).toHaveValue('')
 await expect(page.locator('.table-node-name')).toHaveCount(6)
 await primary.getByRole('button',{name:'卡片视图',exact:true}).click()
 await expect(primary.getByRole('combobox',{name:'卡片密度',exact:true})).toHaveAttribute('data-value','compact')
})

